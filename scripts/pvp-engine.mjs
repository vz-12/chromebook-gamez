/* A browser that writes down every request, and every script it is asked to load. */
function recorder(win) {
  win.__net = [];
  win.fetch = (u) => { win.__net.push('fetch ' + String(u)); return Promise.reject(new Error('offline')); };
  const make = win.document.createElement;
  win.document.createElement = tag => {
    const el = make(tag);
    if (String(tag).toLowerCase() === 'script') {
      let src = '';
      Object.defineProperty(el, 'src', { get: () => src, set: v => { src = v; win.__net.push('script ' + v); } });
    }
    return el;
  };
}
/* And enough more DOM for PvP's waiting room (match.js): an element finds
   what its innerHTML would have held, one stand-in per selector. */
function rooms(win) {
  const make = win.document.createElement;
  win.document.createElement = tag => {
    const el = make(tag);
    const q = {};
    el.querySelector = sel => q[sel] || (q[sel] = { textContent: '', hidden: false, addEventListener(t, f) { (this.__on = this.__on || {})[t] = f; }, style: {}, appendChild() {},
                                                    classList: { toggle() {}, add() {}, remove() {} } });
    el.__q = q;
    return el;
  };
}
